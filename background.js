const BLOCK_RE = /^###\s*БЛОК:\s*([A-Z0-9_]+)\s*$([\s\S]*?)^###\s*КОНЕЦ БЛОКА\s*$/gmi;

let blockCache = { src: null, map: {} };

function knowledgeBlocks(systemPrompt) {
  if (blockCache.src === systemPrompt) return blockCache.map;
  const map = {};
  BLOCK_RE.lastIndex = 0;
  let m;
  while ((m = BLOCK_RE.exec(systemPrompt || '')) !== null) {
    map[m[1].toUpperCase()] = m[2].trim();
  }
  blockCache = { src: systemPrompt, map };
  return map;
}

