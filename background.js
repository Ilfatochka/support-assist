async function pickTopic(c, userText, topics) {
  const short = userText.slice(-1200);
  try {
    const raw = c.useDeepInfra && c.diKey
      ? await askDeepInfra({ ...c, systemPrompt: TOPIC_ASK }, short)
      : await askAnthropic({ ...c, systemPrompt: TOPIC_ASK }, short);
    const out = String(raw.text || raw || '');

    const tm = out.match(/ТЕМА:\s*([a-zа-яё]+)/i) || out.toLowerCase().match(/[a-zа-яё]+/);
    const topic = tm && topics.includes(tm[1] ? tm[1].toLowerCase() : tm[0]) 
      ? (tm[1] ? tm[1].toLowerCase() : tm[0]) : null;

    const pm = out.match(/ПРОБОВАЛ:\s*(.+)/i);
    let tried = pm ? pm[1].trim().replace(/\s+/g, ' ').slice(0, 200) : '';
    if (/^(ничего|нет|—|-)\.?$/i.test(tried)) tried = '';

    return { topic, tried };
  } catch (e) {
    // Тему определить не вышло — не эскалация: отдаём всю базу, как раньше.
  }
  return { topic: null, tried: '' };
}

