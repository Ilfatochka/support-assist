// Вложения CRM лежат на внешних хостах (s3, api.telegram.org). Из content script fetch к ним
// упирается в CORS, поэтому тянем их отсюда: у service worker есть права
// расширения на этот домен, и политика страницы на него не действует.
// Возвращаем base64 — content script уже сам ужмёт через canvas.
async function fetchImage(url) {
  if (!/^https:\/\//.test(url || '')) throw new Error('плохой адрес картинки');
  const res = await fetch(url);
  if (!res.ok) throw new Error('картинка недоступна: HTTP ' + res.status);
  const buf = await res.arrayBuffer();
  if (buf.byteLength > 12 * 1024 * 1024) throw new Error('картинка слишком большая');
  let bin = '';
  const bytes = new Uint8Array(buf);
  const CHUNK = 0x8000;   // по частям, иначе String.fromCharCode падает на больших файлах
  for (let i = 0; i < bytes.length; i += CHUNK) {
    bin += String.fromCharCode.apply(null, bytes.subarray(i, i + CHUNK));
  }
  return {
    media_type: res.headers.get('content-type') || 'image/jpeg',
    data: btoa(bin),
  };
}

chrome.runtime.onMessage.addListener((msg, _sender, respond) => {
  const run = async () => {
    if (msg.type === 'decide') {
      try {
        const r = await decide(msg.payload);
        await noteApiOk();
        return r;
      } catch (e) {
        await noteApiFail(e.message);
        throw e;
      }
    }
    if (msg.type === 'notify') return await notify(msg.lines);
    if (msg.type === 'report') {
      // С chatId отчёт становится частью ветки диалога: ответ на «✓ Отправлено»
      // уходит клиенту, а не теряется. Без chatId — как раньше, просто текст.
      if (msg.chatId) {
        const id = await tgPostId(msg.text);
        if (id) await linkTg(id, msg.chatId, msg.name);
        return { sent: true, messageId: id };
      }
      await tgSend(msg.text);
      return { sent: true };
    }
    // Карточка эскалации: возвращаем id, чтобы content.js знал, что связка есть
    if (msg.type === 'escalateCard') {
      const id = await tgPostId(msg.text);
      await linkTg(id, msg.chatId, msg.name);
      await watchChat(msg.chatId, msg.name);
      // Переписку шлём следом, отдельными сообщениями. Раньше в Telegram
      // уходили четыре строки разбора, и оператор всё равно открывал CRM,
      // чтобы понять, о чём речь. Одним сообщением она не влезает: у
      // Telegram потолок 4096 знаков.
      for (const part of splitForTg(msg.history)) {
        await tgSend(part).catch(() => {});
      }
      return { messageId: id };
    }
    // Новая реплика клиента в диалоге, за которым следим
    if (msg.type === 'clientSaid') {
      const id = await tgPostId(msg.text);
      await linkTg(id, msg.chatId, msg.name);
      // Клиент написал снова — значит опять ждёт, отметку «ответили» снимаем.
      const { tgWatch = {} } = await chrome.storage.local.get(['tgWatch']);
      if (tgWatch[msg.chatId]) {
        tgWatch[msg.chatId].answered = false;
        tgWatch[msg.chatId].ts = Date.now();
        await chrome.storage.local.set({ tgWatch });
      }
      return { messageId: id };
    }
    if (msg.type === 'cfg') return await cfg();
    if (msg.type === 'tgDiagnose') return await tgDiagnose();
    if (msg.type === 'fetchImage') return await fetchImage(msg.url);
    if (msg.type === 'bump') {   // копим статистику для сигнала жизни
      const { hbStats = { done: 0, replied: 0, escalated: 0 } } = await chrome.storage.local.get('hbStats');
      hbStats.done += msg.done || 0;
      hbStats.replied += msg.replied || 0;
      hbStats.escalated += msg.escalated || 0;
      await chrome.storage.local.set({ hbStats });
      return { ok: true };
    }
    throw new Error('неизвестная команда');
  };
  run().then((data) => respond({ ok: true, data }))
       .catch((e) => respond({ ok: false, error: e.message }));
  return true; // ответ придёт асинхронно
});
