// ---------- отчёт кнопки «Что-то не работает» ----------
//
// С 1.3.14 приложение само собирает состояние и отправляет его в чат. Отчёт —
// обращение клиента, а не вывод админ-бота, хотя в нём есть «Стабильный ключ»
// и «ID:». Строки помечены метками, поэтому разбираем их кодом: модель
// правило из промпта выполняет через раз.
const REPORT_LABELS = /^\s*(⚠️\s*)?(что-то не работает|клиент\s*:|id\s*:|ключ\s*:|тоннель\s*:|белый список\s*:|раздельное туннелирование\s*:|пинг\s*:|настройки\s*:)/i;

function parseReport(text) {
  const t = String(text || '');
  if (!/что-то не работает/i.test(t) || !/тоннель\s*:/i.test(t)) return null;
  // Всё, что не помечено меткой отчёта, — слова клиента. По ним и решаем,
  // пришёл отчёт один или вместе с жалобой.
  const own = t.split(/\n+/)
    .filter((l) => l.trim() && !REPORT_LABELS.test(l))
    .join(' ')
    .replace(/[\s\p{P}]+/gu, ' ')
    .trim();
  return {
    only: own.length < 3,
    own,
    whitelistOff: /белый список\s*:\s*выключен/i.test(t),
    splitOff: /раздельное туннелирование\s*:\s*выключено/i.test(t),
    keyMissing: /ключ\s*:\s*не найден/i.test(t),
  };
}

