// Вся база одной строкой — по ней сверяем, не выдумала ли модель ссылку.
// Кэш по ссылке на объект: knowledgeBlocks отдаёт один и тот же map, пока
// не сменился текст базы.
let flatCache = { map: null, text: '' };
function blocksFlat(blocks) {
  if (flatCache.map === blocks) return flatCache.text;
  const text = Object.values(blocks || {}).join('\n').toLowerCase();
  flatCache = { map: blocks, text };
  return text;
}

function checkFreeAnswer(text, blocks) {
  const flat = blocksFlat(blocks);

  // Нумерованный шаг — это инструкция. Инструкции живут только в блоках,
  // иначе весь смысл блоков теряется.
  if (/^\s*\d+[.)]\s/m.test(text)) {
    return { error: 'свободный ответ содержит пошаговую инструкцию', stop: 'инструкция в свободном ответе' };
  }

  // Ссылки и домены — только те, что дословно есть в базе. Выдуманный адрес
  // в переписке живёт вечно и приводит клиента не туда.
  const links = text.match(/https?:\/\/[^\s)»"']+|(?:[a-z0-9-]+\.)+(?:ru|com|online|org|net|io|app|space|tv)\b/gi) || [];
  for (const raw of links) {
    const l = raw.toLowerCase().replace(/[.,;:!?]+$/, '');
    if (!flat.includes(l)) return { error: `ссылка «${l}» не из базы знаний`, stop: 'выдуманная ссылка' };
  }

  // Имена ботов и каналов — так же.
  const handles = text.match(/@[a-z0-9_]{3,}/gi) || [];
  for (const h of handles) {
    if (!flat.includes(h.toLowerCase())) return { error: `имя «${h}» не из базы знаний`, stop: 'выдуманное имя' };
  }

  // Суммы. Баланс и списание подставляет система из кабинета, а цены тарифов
  // модель называть не должна вовсе: они меняются, а ответ остаётся.
  const money = text.match(/\d[\d\s.,]*\s*(?:₽|руб\w*)/gi) || [];
  for (const m of money) {
    const digits = (m.match(/\d+/) || [''])[0];
    const near = flat.includes(`${digits}₽`) || flat.includes(`${digits} ₽`)
      || flat.includes(`${digits}руб`) || flat.includes(`${digits} руб`);
    if (!near) return { error: `сумма «${m.trim()}» не из базы знаний`, stop: 'выдуманная сумма' };
  }

  return null;
}

