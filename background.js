// Возвращает решение по переписке. Провайдер выбирается в настройках.
// ---------- примеры из работы операторов ----------
//
// 1421 разобранный ответ живых операторов: вопрос клиента и блоки, которые
// человек выбрал. Правила «когда применять» модель читает и всё равно берёт
// привычное — а похожий случай с готовым решением работает как показ, а не
// как уговор. Это и есть «делай как оператор в таком же случае».

let EX = null;             // [{q, b}]
let EX_IDX = null;         // слово -> [номера примеров]

const EX_STOP = new Set(('а без бы был была было были в вам вас вот все всё всего вы где да для '
  + 'до его ее её если есть еще ещё же за и из или им их как кто когда ко ли мне меня мы на не '
  + 'нет ни но ну о об он она они от очень по под после при про с сам свой себя со так там те '
  + 'то тоже только тот ту ты у уже что чтобы эта эти это этого этом этот я мой моя мои просто '
  + 'здравствуйте добрый день вечер утро привет пожалуйста спасибо подскажите скажите помогите '
  + 'нужно надо хочу могу можно').split(' '));

function exWords(s) {
  return [...new Set((s.toLowerCase().match(/[а-яёa-z0-9]{3,}/g) || [])
    .filter((w) => !EX_STOP.has(w)).map((w) => w.slice(0, 6)))];
}

async function loadExamples() {
  if (EX) return EX;
  try {
    const r = await fetch(chrome.runtime.getURL('examples.json'));
    EX = await r.json();
  } catch { EX = []; }
  EX_IDX = new Map();
  EX.forEach((e, i) => {
    for (const w of exWords(e.q)) {
      if (!EX_IDX.has(w)) EX_IDX.set(w, []);
      EX_IDX.get(w).push(i);
    }
  });
  return EX;
}

// Похожие случаи по редким общим словам: частое слово вроде «работает» есть
// почти везде и ничего не различает, поэтому вес обратен частоте.
async function similarCases(text, want = 5, topic = '') {
  await loadExamples();
  if (!EX.length) return [];
  const words = exWords(text);
  // На «не работает» похоже всё подряд: без трёх различающих слов не ищем.
  if (words.length < 3) return [];

  const score = new Map();
  for (const w of words) {
    const hits = EX_IDX.get(w);
    if (!hits || hits.length > EX.length / 6) continue;   // слишком частое
    const weight = 1 / Math.log(2 + hits.length);
    for (const i of hits) score.set(i, (score.get(i) || 0) + weight);
  }
  if (!score.size) return [];

  const best = [...score.entries()].sort((a, b) => b[1] - a[1]);
  // Порог относительный: у длинного вопроса совпадений много и веса выше,
  // у короткого — наоборот. Берём то, что близко к лучшему найденному,
  // и отсекаем совсем слабое.
  const top = best[0][1];
  const floor = Math.max(0.5, top * 0.45);
  const out = [];
  const usedBlocks = new Set();
  for (const [i, s] of best) {
    if (s < floor) break;
    const e = EX[i];
    const key = e.b.join(',');
    // Пять примеров с одним и тем же блоком ничему не учат — берём разные.
    if (usedBlocks.has(key) && out.length >= 2) continue;
    usedBlocks.add(key);
    out.push(e);
    if (out.length >= want) break;
  }
  return out;
}

// Собирает промпт под одну тему: правила целиком + общие разделы FAQ
// + разделы этой темы. Разделы помечены комментариями <!--ТЕМА:X--> прямо
// в базе знаний, поэтому файл у оператора остаётся один.
function topicPrompt(kb, topic) {
  const i = kb.indexOf('# FAQ');
  if (i < 0) return kb;                       // меток нет — работаем по-старому
  const head = kb.slice(0, i);
  const parts = kb.slice(i).split(/(?=<!--ТЕМА:)/);
  const keep = parts.filter((s) => {
    const m = s.match(/^<!--ТЕМА:([a-zа-яё]+)-->/);
    return !m || m[1] === 'общее' || m[1] === topic;
  });
  return head + keep.join('');
}

function knownTopics(kb) {
  return [...new Set([...kb.matchAll(/<!--ТЕМА:([a-zа-яё]+)-->/g)].map((m) => m[1]))]
    .filter((t) => t !== 'общее');
}

