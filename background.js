// Подставляет {имя} в тексте блока значениями из vars.
// Не нашлось значения — блок не отправляем: фигурные скобки в глазах клиента
// хуже, чем ожидание оператора.
function fillVars(text, vars) {
  const missing = [];
  const out = text.replace(/\{([^{}\n]{1,40})\}/g, (m, key) => {
    const v = vars[key.trim()];
    if (v === undefined || v === null || v === '') { missing.push(key.trim()); return m; }
    return String(v);
  });
  return { out, missing };
}

