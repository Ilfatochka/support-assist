// Из ответа модели достаём JSON, даже если он завёрнут в ```json
function parseDecision(raw) {
  let t = (raw || '').trim();
  const fence = t.match(/```(?:json)?\s*([\s\S]*?)```/i);
  if (fence) t = fence[1].trim();
  const a = t.indexOf('{');
  const b = t.lastIndexOf('}');
  if (a !== -1 && b > a) t = t.slice(a, b + 1);
  try { return JSON.parse(t); } catch (e) { /* пробуем починить ниже */ }

  // Ответ оборвался на полуслове. Дальше — попытки спасти, но с одним общим
  // правилом: если в ответе был ключ "blocks", а спасённый результат его
  // потерял, спасать нельзя. Иначе клиент получит приветствие без инструкции
  // и примет его за ответ.
  const salvage = t.slice(t.indexOf('{'));
  const hadBlocks = /"blocks"\s*:/.test(salvage);
  const blocks = (() => {
    const m = salvage.match(/"blocks"\s*:\s*\[([^\]]*)\]/);
    if (!m) return null;
    const ids = m[1].match(/"([A-Z0-9_]+)"/g);
    return ids ? ids.map((s) => s.replace(/"/g, '')) : [];
  })();
  const keeps = (d) => !hadBlocks || (Array.isArray(d.blocks) && d.blocks.length === (blocks || []).length);

  // Закрываем скобку, отбросив хвост после последней целой пары "ключ": "значение".
  const cut = salvage.lastIndexOf('",');
  if (cut > 0) {
    try {
      const d = JSON.parse(salvage.slice(0, cut + 1) + '}');
      if (blocks && blocks.length && !d.blocks) d.blocks = blocks;
      if (keeps(d)) { d.salvaged = true; return d; }
    } catch (e) { /* ниже */ }
  }

  // Последняя попытка: вытащить поля регулярками.
  const field = (name) => {
    const m = salvage.match(new RegExp('"' + name + '"\\s*:\\s*"((?:[^"\\\\]|\\\\.)*)'));
    return m ? m[1].replace(/\\"/g, '"').replace(/\\n/g, '\n') : null;
  };
  const action = field('action');
  const message = field('message');
  const intro = field('intro');

  if (hadBlocks && blocks === null) throw new Error('обрыв внутри blocks');

  if (action && (message || intro || (blocks && blocks.length))) {
    return {
      action,
      message: message || '',
      intro: intro || '',
      outro: field('outro') || '',
      blocks: blocks || [],
      reason: field('reason') || 'ответ модели был обрезан',
      topic: field('topic') || '—',
      salvaged: true,
    };
  }
  throw new Error('не разобрать JSON');
}

